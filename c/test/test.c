static int
test_b(void)
{
	Rijndael_Ctx r = {};
	Rijndael_ECB_Ctx ecb = {};
	uint8_t block[32] = {};
	uint8_t key[32] = {};
	for (size_t i = 0; i < sizeof(RIJN_TEST) / sizeof(RIJN_TEST[0]); i++) {
		Rijndael_Vectors v = RIJN_TEST[i];
		int bl = v.blocklen / 8;
		int kl = v.keylen / 8;
		rijndael_init(&r, key, kl, bl);
		rijndael_set_mode_ECB(&ecb, &r);

		rijndael_encrypt_ECB(&ecb, block, bl, block, bl);
		if (memcmp(v.a, block, bl) != 0) {
			printf("test_b enc failed: (%d, %d)\n", v.blocklen, v.keylen);
			return 1;
		}
		rijndael_encrypt_ECB(&ecb, block, bl, block, bl);
		if (memcmp(v.b, block, bl) != 0) {
			printf("test_b enc failed: (%d, %d)\n", v.blocklen, v.keylen);
			return 1;
		}
		rijndael_decrypt_ECB(&ecb, block, bl, block, bl);
		if (memcmp(v.a, block, bl) != 0) {
			printf("test_b dec failed: (%d, %d)\n", v.blocklen, v.keylen);
			return 1;
		}

		memset(block, 0, sizeof(block));
	}
	return 0;
}

